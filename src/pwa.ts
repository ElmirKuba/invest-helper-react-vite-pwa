// src/pwa.ts
import { registerSW } from 'virtual:pwa-register';

/**
 * Мы сначала объявляем переменную updateSW,
 * а затем присваиваем результат registerSW - так внутри onNeedRefresh
 * можно будет вызвать updateSW(...) (обход порядка определения).
 */
let updateSW: (reloadPage?: boolean) => Promise<void> | undefined;

updateSW = registerSW({
  immediate: true, // можно true — регистрируем сразу при загрузке
  onNeedRefresh() {
    // Очень простой prompt — как вы просили
    const agree = confirm('Доступна новая версия приложения. Обновить сейчас?');

    if (agree) {
      // Просим активировать новую версию и перезагрузить страницу.
      // Аргумент true старается сразу перезапустить клиентов.
      updateSW?.(true)
        // на случай, если встроенный механизм не перезагрузит,
        // делаем запасную перезагрузку через небольшой таймаут
        .then(() => {
          setTimeout(() => {
            try {
              location.reload();
            } catch (e) {
              /* no-op */
            }
          }, 300);
        })
        .catch(() => {
          // Если по какой-то причине промис упал — принудительная перезагрузка
          try {
            location.reload();
          } catch (e) {
            /* no-op */
          }
        });
    } else {
      // Если пользователь отказался — ничего не делаем:
      // новая версия останется в state 'waiting' до ручной перезагрузки/закрытия вкладки.
      // Это и есть контролируемое поведение.
      // Можно при желании логировать или показать ненавязчивую подсказку.
      console.log('Пользователь отказался обновляться — останемся на текущей версии.');
    }
  },
  onOfflineReady() {
    console.log('Приложение готово работать оффлайн.');
  },
});

export { updateSW };
